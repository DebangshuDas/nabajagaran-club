CREATE TABLE homepage_configurations (
    id BIGINT PRIMARY KEY,
    hero_title VARCHAR(200) NOT NULL,
    hero_subtitle VARCHAR(500),
    hero_image_url VARCHAR(255),
    cta_text VARCHAR(100),
    cta_url VARCHAR(255),
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT ck_homepage_configurations_singleton CHECK (id = 1)
);

CREATE TABLE homepage_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homepage_configuration_id BIGINT NOT NULL,
    section_type VARCHAR(30) NOT NULL,
    is_visible BOOLEAN NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_homepage_sections_configuration
        FOREIGN KEY (homepage_configuration_id) REFERENCES homepage_configurations (id) ON DELETE CASCADE,
    CONSTRAINT uk_homepage_sections_type UNIQUE (homepage_configuration_id, section_type)
);

CREATE TABLE homepage_section_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homepage_section_id BIGINT NOT NULL,
    content_key VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_homepage_section_items_section
        FOREIGN KEY (homepage_section_id) REFERENCES homepage_sections (id) ON DELETE CASCADE,
    CONSTRAINT uk_homepage_section_items_key UNIQUE (homepage_section_id, content_key)
);

CREATE INDEX idx_homepage_sections_order
    ON homepage_sections (homepage_configuration_id, display_order);
CREATE INDEX idx_homepage_section_items_order
    ON homepage_section_items (homepage_section_id, display_order);

