INSERT INTO homepage_section_items (homepage_section_id, content_key, display_order)
SELECT section.id, CAST(content.id AS VARCHAR), content.display_order
FROM homepage_sections section
JOIN (
    SELECT id, ROW_NUMBER() OVER (ORDER BY start_at, id) - 1 AS display_order
    FROM events
    WHERE is_published = TRUE AND deleted = FALSE
    ORDER BY start_at, id
    LIMIT 3
) content ON section.section_type = 'EVENTS'
WHERE section.homepage_configuration_id = 1;

INSERT INTO homepage_section_items (homepage_section_id, content_key, display_order)
SELECT section.id, CAST(content.id AS VARCHAR), content.display_order
FROM homepage_sections section
JOIN (
    SELECT id, ROW_NUMBER() OVER (ORDER BY published_at DESC NULLS LAST, id DESC) - 1 AS display_order
    FROM announcements
    WHERE is_published = TRUE AND deleted = FALSE
    ORDER BY published_at DESC NULLS LAST, id DESC
    LIMIT 3
) content ON section.section_type = 'ANNOUNCEMENTS'
WHERE section.homepage_configuration_id = 1;
