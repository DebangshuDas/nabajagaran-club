CREATE TABLE festival_programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    festival_edition_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    programme_date DATE NOT NULL,
    start_time TIME(6) WITHOUT TIME ZONE NOT NULL,
    end_time TIME(6) WITHOUT TIME ZONE,
    venue VARCHAR(255),
    display_order INTEGER NOT NULL DEFAULT 0,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_festival_programmes_edition
        FOREIGN KEY (festival_edition_id) REFERENCES festival_editions (id),
    CONSTRAINT chk_festival_programmes_display_order
        CHECK (display_order >= 0)
);

CREATE INDEX idx_festival_programmes_edition_date_order
    ON festival_programmes (festival_edition_id, programme_date, display_order, start_time, deleted);

CREATE INDEX idx_festival_programmes_publication
    ON festival_programmes (is_published, deleted, programme_date);
