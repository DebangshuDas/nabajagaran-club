CREATE TABLE IF NOT EXISTS club_information (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    tagline VARCHAR(200),
    description TEXT,
    mission TEXT,
    founding_year INTEGER,
    address VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    country VARCHAR(100),
    postal_code VARCHAR(20),
    email VARCHAR(150),
    phone VARCHAR(50),
    website VARCHAR(255),
    facebook_url VARCHAR(255),
    instagram_url VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_club_information_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS club_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_name VARCHAR(150) NOT NULL,
    tagline VARCHAR(200),
    description TEXT,
    mission TEXT,
    founded_year INTEGER,
    address VARCHAR(200),
    city VARCHAR(100),
    state VARCHAR(100),
    country VARCHAR(100),
    postal_code VARCHAR(50),
    email VARCHAR(150),
    phone VARCHAR(50),
    website VARCHAR(255),
    facebook_url VARCHAR(255),
    instagram_url VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS business_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_business_categories_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(150),
    phone VARCHAR(50),
    membership_status VARCHAR(20) NOT NULL,
    join_date DATE,
    expiry_date DATE,
    notes TEXT,
    is_public_profile BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_members_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_information_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    is_published BOOLEAN NOT NULL,
    published_at TIMESTAMP(6) WITHOUT TIME ZONE,
    audience VARCHAR(50),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_announcements_club_information
        FOREIGN KEY (club_information_id) REFERENCES club_information (id)
);

CREATE TABLE IF NOT EXISTS businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_information_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL,
    description TEXT,
    website VARCHAR(255),
    email VARCHAR(150),
    phone VARCHAR(50),
    address VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    country VARCHAR(100),
    postal_code VARCHAR(20),
    latitude NUMERIC(9, 6),
    longitude NUMERIC(9, 6),
    approval_status VARCHAR(20) NOT NULL,
    is_featured BOOLEAN NOT NULL,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_businesses_slug UNIQUE (slug),
    CONSTRAINT fk_businesses_club_information
        FOREIGN KEY (club_information_id) REFERENCES club_information (id),
    CONSTRAINT fk_businesses_category
        FOREIGN KEY (category_id) REFERENCES business_categories (id)
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_information_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    short_description VARCHAR(500),
    event_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    start_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    end_at TIMESTAMP(6) WITHOUT TIME ZONE,
    venue VARCHAR(255),
    address VARCHAR(255),
    is_published BOOLEAN NOT NULL,
    capacity INTEGER,
    image_url VARCHAR(255),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_events_slug UNIQUE (slug),
    CONSTRAINT fk_events_club_information
        FOREIGN KEY (club_information_id) REFERENCES club_information (id)
);

