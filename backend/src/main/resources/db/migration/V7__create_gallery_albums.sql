CREATE TABLE gallery_albums (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_information_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    category VARCHAR(50),
    cover_image_id BIGINT,
    event_id BIGINT,
    initiative_id BIGINT,
    festival_edition_id BIGINT,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT fk_gallery_albums_club_information
        FOREIGN KEY (club_information_id) REFERENCES club_information (id),
    CONSTRAINT fk_gallery_albums_event
        FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_gallery_albums_initiative
        FOREIGN KEY (initiative_id) REFERENCES community_initiatives (id),
    CONSTRAINT fk_gallery_albums_festival_edition
        FOREIGN KEY (festival_edition_id) REFERENCES festival_editions (id),
    CONSTRAINT ck_gallery_albums_single_association CHECK (
        (event_id IS NULL OR (initiative_id IS NULL AND festival_edition_id IS NULL))
        AND (initiative_id IS NULL OR (event_id IS NULL AND festival_edition_id IS NULL))
        AND (festival_edition_id IS NULL OR (event_id IS NULL AND initiative_id IS NULL))
    )
);

INSERT INTO gallery_albums (
    club_information_id,
    title,
    category,
    is_published,
    created_at,
    updated_at,
    deleted
)
SELECT
    club_information.id,
    'General gallery',
    'GENERAL',
    EXISTS (
        SELECT 1
        FROM gallery_images
        WHERE gallery_images.club_information_id = club_information.id
            AND gallery_images.deleted = FALSE
            AND gallery_images.is_public = TRUE
    ),
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP,
    FALSE
FROM club_information
WHERE EXISTS (
    SELECT 1
    FROM gallery_images
    WHERE gallery_images.club_information_id = club_information.id
);

