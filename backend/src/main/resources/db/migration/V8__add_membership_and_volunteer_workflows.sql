CREATE TABLE volunteers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_registration_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    activated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    deactivated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT ck_volunteers_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT uk_volunteers_registration_id UNIQUE (volunteer_registration_id),
    CONSTRAINT fk_volunteers_registration
        FOREIGN KEY (volunteer_registration_id) REFERENCES volunteer_registrations (id)
);

-- Legacy approval does not prove current activity: use INACTIVE, leave activated_at unknown,
-- and use migration time only for the new row's audit timestamps.
INSERT INTO volunteers (
    volunteer_registration_id,
    status,
    activated_at,
    deactivated_at,
    created_at,
    updated_at,
    deleted,
    deleted_at
)
SELECT
    registration.id,
    'INACTIVE',
    NULL,
    NULL,
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP,
    registration.deleted,
    registration.deleted_at
FROM volunteer_registrations registration
WHERE registration.status = 'APPROVED'
  AND NOT EXISTS (
      SELECT 1
      FROM volunteers existing
      WHERE existing.volunteer_registration_id = registration.id
  );

CREATE INDEX idx_volunteers_status ON volunteers (status);
CREATE INDEX idx_volunteers_deleted ON volunteers (deleted);
