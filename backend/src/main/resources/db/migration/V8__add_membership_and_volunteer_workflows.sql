-- Only unambiguous active pending emails are backfilled; duplicate legacy groups remain reviewable with NULL keys.
UPDATE volunteer_registrations
SET pending_email = LOWER(TRIM(email))
WHERE status = 'PENDING'
  AND deleted = FALSE
  AND NOT EXISTS (
      SELECT 1
      FROM volunteer_registrations duplicate
      WHERE duplicate.status = 'PENDING'
        AND duplicate.deleted = FALSE
        AND LOWER(TRIM(duplicate.email)) = LOWER(TRIM(volunteer_registrations.email))
        AND duplicate.id <> volunteer_registrations.id
  );

CREATE UNIQUE INDEX uk_volunteer_registrations_pending_email
    ON volunteer_registrations (pending_email);

CREATE TABLE membership_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50),
    address VARCHAR(255),
    occupation VARCHAR(150),
    reason_for_joining TEXT,
    additional_message TEXT,
    status VARCHAR(20) NOT NULL,
    pending_email VARCHAR(150),
    member_id BIGINT,
    submitted_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    reviewed_by VARCHAR(150),
    internal_notes TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT ck_membership_applications_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT uk_membership_applications_member_id UNIQUE (member_id),
    CONSTRAINT uk_membership_applications_pending_email UNIQUE (pending_email),
    CONSTRAINT fk_membership_applications_member
        FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_membership_applications_status
