CREATE TABLE festivals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL,
    description TEXT,
    history TEXT,
    cover_image_url VARCHAR(255),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT uk_festivals_slug UNIQUE (slug)
);

CREATE TABLE festival_editions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    festival_id BIGINT NOT NULL,
    festival_year INTEGER NOT NULL,
    theme VARCHAR(200),
    description TEXT,
    start_date DATE,
    end_date DATE,
    venue VARCHAR(255),
    address VARCHAR(255),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    active_year INTEGER,
    CONSTRAINT fk_festival_editions_festival
        FOREIGN KEY (festival_id) REFERENCES festivals (id),
    CONSTRAINT chk_festival_editions_year
        CHECK (festival_year BETWEEN 1 AND 9999)
);

CREATE UNIQUE INDEX uk_festival_editions_festival_year_active
    ON festival_editions (festival_id, active_year);

CREATE INDEX idx_festival_editions_festival
    ON festival_editions (festival_id, deleted);

CREATE INDEX idx_festival_editions_published
    ON festival_editions (is_published, deleted);

CREATE TABLE festival_edition_events (
    festival_edition_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    CONSTRAINT pk_festival_edition_events PRIMARY KEY (festival_edition_id, event_id),
    CONSTRAINT fk_festival_edition_events_edition
        FOREIGN KEY (festival_edition_id) REFERENCES festival_editions (id),
    CONSTRAINT fk_festival_edition_events_event
        FOREIGN KEY (event_id) REFERENCES events (id)
);

CREATE INDEX idx_festival_edition_events_event
    ON festival_edition_events (event_id);

CREATE TABLE festival_edition_gallery_images (
    festival_edition_id BIGINT NOT NULL,
    gallery_image_id BIGINT NOT NULL,
    CONSTRAINT pk_festival_edition_gallery_images
        PRIMARY KEY (festival_edition_id, gallery_image_id),
    CONSTRAINT fk_festival_edition_gallery_images_edition
        FOREIGN KEY (festival_edition_id) REFERENCES festival_editions (id),
    CONSTRAINT fk_festival_edition_gallery_images_image
        FOREIGN KEY (gallery_image_id) REFERENCES gallery_images (id)
);

CREATE INDEX idx_festival_edition_gallery_images_image
    ON festival_edition_gallery_images (gallery_image_id);

CREATE TABLE festival_edition_sponsors (
    festival_edition_id BIGINT NOT NULL,
    sponsor_id BIGINT NOT NULL,
    CONSTRAINT pk_festival_edition_sponsors PRIMARY KEY (festival_edition_id, sponsor_id),
    CONSTRAINT fk_festival_edition_sponsors_edition
        FOREIGN KEY (festival_edition_id) REFERENCES festival_editions (id),
    CONSTRAINT fk_festival_edition_sponsors_sponsor
        FOREIGN KEY (sponsor_id) REFERENCES sponsors (id)
);

CREATE INDEX idx_festival_edition_sponsors_sponsor
    ON festival_edition_sponsors (sponsor_id);
